export function findTeamId(input: string): number | null {
  const normalized = input.toLowerCase().trim()

  if (normalized in teamIdByName) {
    return teamIdByName[normalized]
  }

  const entry = Object.entries(teamIdByName).find(([key]) =>
    key.includes(normalized) || normalized.includes(key)
  )
  return entry ? entry[1] : null
}
